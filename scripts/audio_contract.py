#!/usr/bin/env python3
"""Build an honest audio-direction contract for integrated-audio video runs.

This stage never synthesizes a standalone voice.  It freezes the customer's
voice direction so the video model can create picture, voice and lip sync in a
later test segment.  An existing customer-supplied master audio file may be
bound, but it is not generated by this module.
"""
from __future__ import annotations

import argparse
import hashlib
import html
import json
import os
import sys

from project_utils import (atomic_write_bytes, atomic_write_json,
                           require_contained_path)


HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
AUDIO_MODES = {"talking_presenter", "voiceover", "music_only"}
VOICE_OWNER = "video_model_integrated_audio"
FIRST_GENERATED_AUDITION_STAGE = "test_segment"
CHOICE_KIND = "audio_stage_choice"
VOICE_BRIEF_KIND = "integrated_video_voice_brief"
CONTRACT_KIND = "integrated_video_audio_direction_contract"
PREVIEW_PREFIX = "audio_preview."
_NONE_BGM = {"none", "off", "no", "无", "不需要", "不要"}


def _sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _canonical_bytes(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def _canonical_sha256(value):
    return hashlib.sha256(_canonical_bytes(value)).hexdigest()


def _text(value):
    return " ".join(str(value or "").replace("\x00", "").split())


def _plain(value):
    return html.escape(_text(value), quote=False)


def _required_text(value, error):
    value = _text(value)
    if not value:
        raise ValueError(error)
    return value


def normalize_choice(choice):
    """Validate all customer decisions before any stage transaction starts."""
    if not isinstance(choice, dict):
        raise ValueError("AUDIO_CHOICE_OBJECT_REQUIRED")
    mode = _text(choice.get("mode") or choice.get("audio_mode"))
    if mode not in AUDIO_MODES:
        raise ValueError("AUDIO_CHOICE_MODE_REQUIRED")
    bgm = _required_text(choice.get("bgm"), "AUDIO_CHOICE_BGM_DECISION_REQUIRED")
    normalized = {
        "schema_version": 2,
        "kind": CHOICE_KIND,
        "mode": mode,
        "bgm": bgm,
        "feedback": _text(choice.get("feedback")),
    }
    if mode == "music_only":
        if bgm.lower() in _NONE_BGM:
            raise ValueError("MUSIC_ONLY_BGM_REQUIRED")
        return normalized

    normalized.update({
        "language": _required_text(
            choice.get("language"), "AUDIO_CHOICE_LANGUAGE_REQUIRED"),
        "voice_type": _required_text(
            choice.get("voice_type"), "AUDIO_CHOICE_VOICE_TYPE_REQUIRED"),
        "tone": _required_text(
            choice.get("tone"), "AUDIO_CHOICE_TONE_REQUIRED"),
    })
    for field in (
            "speaker_role", "speaker_profile", "pace", "articulation",
            "emphasis", "ending"):
        value = _text(choice.get(field))
        if value:
            normalized[field] = value
    pronunciation = choice.get("pronunciation") or {}
    if not isinstance(pronunciation, dict):
        raise ValueError("AUDIO_CHOICE_PRONUNCIATION_OBJECT_REQUIRED")
    normalized_pronunciation = {
        _required_text(key, "AUDIO_CHOICE_PRONUNCIATION_TERM_REQUIRED"):
        _required_text(value, "AUDIO_CHOICE_PRONUNCIATION_VALUE_REQUIRED")
        for key, value in pronunciation.items()
    }
    if normalized_pronunciation:
        normalized["pronunciation"] = normalized_pronunciation
    avoid = choice.get("avoid") or []
    if not isinstance(avoid, list):
        raise ValueError("AUDIO_CHOICE_AVOID_LIST_REQUIRED")
    normalized_avoid = [_text(item) for item in avoid if _text(item)]
    if normalized_avoid:
        normalized["avoid"] = normalized_avoid
    return normalized


def compile_voice_brief(choice):
    choice = normalize_choice(choice)
    if choice["mode"] == "music_only":
        return {
            "schema_version": 2,
            "kind": VOICE_BRIEF_KIND,
            "spoken_voice": False,
            "bgm": choice["bgm"],
            "generation_owner": VOICE_OWNER,
        }
    brief = {
        "schema_version": 2,
        "kind": VOICE_BRIEF_KIND,
        "language": choice["language"],
        "voice_type": choice["voice_type"],
        "delivery": {"tone": choice["tone"]},
        "bgm": choice["bgm"],
        "generation_owner": VOICE_OWNER,
        "formal_audio_note": (
            "正式声音、画面与口型由音画一体视频模型生成；第一次真实试听和"
            "口型验收发生在单段测试片，不存在本阶段的独立 TTS 试听。"),
    }
    speaker = {}
    if choice.get("speaker_role"):
        speaker["role"] = choice["speaker_role"]
    if choice.get("speaker_profile"):
        speaker["profile"] = choice["speaker_profile"]
    if speaker:
        brief["speaker"] = speaker
    for field in ("pace", "articulation", "emphasis", "ending"):
        if choice.get(field):
            brief["delivery"][field] = choice[field]
    if choice.get("pronunciation"):
        brief["pronunciation"] = choice["pronunciation"]
    if choice.get("avoid"):
        brief["avoid"] = choice["avoid"]
    return brief


def validate(contract):
    if not isinstance(contract, dict) or contract.get("audio_mode") not in AUDIO_MODES:
        raise ValueError("AUDIO_MODE_REQUIRED")
    mode = contract["audio_mode"]
    if mode != "music_only" and not contract.get("voice_brief"):
        raise ValueError("VOICE_BRIEF_REQUIRED")
    if mode == "voiceover" and contract.get("allow_visible_speech"):
        raise ValueError("VOICEOVER_VISIBLE_SPEECH_FORBIDDEN")
    master = contract.get("master_audio")
    if master:
        path = master.get("path")
        if not path or not os.path.isfile(path):
            raise ValueError("MASTER_AUDIO_MISSING")
        if master.get("sha256") != _sha256(path):
            raise ValueError("MASTER_AUDIO_STALE")

    # Version 1 contracts remain readable so approved historical runs do not
    # become stale merely because the public contract was strengthened.
    if int(contract.get("schema_version") or 1) < 2:
        return contract
    if contract.get("kind") != CONTRACT_KIND:
        raise ValueError("AUDIO_CONTRACT_KIND_INVALID")
    generation = contract.get("generation_contract") or {}
    expected = {
        "voice_owner": VOICE_OWNER,
        "standalone_voice_generation_available": False,
        "stage_generates_playable_audio": False,
        "first_generated_audition_stage": FIRST_GENERATED_AUDITION_STAGE,
    }
    if any(generation.get(key) != value for key, value in expected.items()):
        raise ValueError("AUDIO_GENERATION_OWNERSHIP_INVALID")
    expected_preview = "provided_master_audio" if master else "contract_only"
    if generation.get("preview_kind") != expected_preview:
        raise ValueError("AUDIO_PREVIEW_KIND_INVALID")
    if mode != "music_only":
        brief = contract.get("voice_brief") or {}
        if (brief.get("kind") != VOICE_BRIEF_KIND or
                brief.get("generation_owner") != VOICE_OWNER):
            raise ValueError("VOICE_BRIEF_GENERATION_OWNER_INVALID")
    return contract


def create(mode, *, voice_brief=None, master_path=None):
    owned_brief = dict(voice_brief or {})
    if mode != "music_only" and owned_brief:
        if owned_brief.get("generation_owner") not in (None, VOICE_OWNER):
            raise ValueError("VOICE_BRIEF_GENERATION_OWNER_INVALID")
        if owned_brief.get("kind") not in (None, VOICE_BRIEF_KIND):
            raise ValueError("VOICE_BRIEF_KIND_INVALID")
        owned_brief.setdefault("schema_version", 2)
        owned_brief["kind"] = VOICE_BRIEF_KIND
        owned_brief["generation_owner"] = VOICE_OWNER
        owned_brief.setdefault(
            "formal_audio_note",
            "正式声音、画面与口型由音画一体视频模型生成；第一次真实试听和"
            "口型验收发生在单段测试片，不存在本阶段的独立 TTS 试听。")
    contract = {
        "schema_version": 2,
        "kind": CONTRACT_KIND,
        "audio_mode": mode,
        "voice_brief": owned_brief,
        "allow_visible_speech": mode == "talking_presenter",
        "generation_contract": {
            "voice_owner": VOICE_OWNER,
            "standalone_voice_generation_available": False,
            "stage_generates_playable_audio": False,
            "preview_kind": "provided_master_audio" if master_path else "contract_only",
            "first_generated_audition_stage": FIRST_GENERATED_AUDITION_STAGE,
            "required_test_segment_checks": [
                "non_silent_audio_track", "dialogue_fidelity", "voice_direction",
                "lip_sync",
            ],
        },
    }
    if master_path:
        absolute = os.path.abspath(master_path)
        contract["master_audio"] = {
            "path": absolute, "sha256": _sha256(absolute),
            "origin": "customer_or_existing_asset",
        }
    return validate(contract)


def compile_preview(choice, contract, *, choice_sha256, contract_sha256,
                    voice_brief_sha256, client, run_id):
    """Return a deterministic, non-playable approval view of voice direction."""
    validate(contract)
    mode = contract["audio_mode"]
    voice = contract.get("voice_brief") or {}
    generation = contract.get("generation_contract") or {}
    binding = json.dumps({
        "schema_version": 2,
        "stage": "audio",
        "choice_sha256": choice_sha256,
        "voice_brief_sha256": voice_brief_sha256,
        "contract_sha256": contract_sha256,
    }, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    mode_label = {
        "talking_presenter": "出镜讲解（视频模型音画一体）",
        "voiceover": "画外旁白（视频模型音画一体）",
        "music_only": "纯音乐 / 无人声",
    }[mode]
    lines = [
        "<!-- approval-preview-binding:%s -->" % binding,
        "# %s 声音方案确认" % _plain(client),
        "",
        "> 本阶段只冻结声音模式、音色方向、讲述语气和 BGM 决策；"
        "不会调用独立 TTS，也不会生成一条可试听的配音。",
        "",
        "## 已选声音方向",
        "",
        "- 声音模式：%s" % mode_label,
        "- BGM：%s" % (_plain((choice or {}).get("bgm") or voice.get("bgm")) or "未指定"),
    ]
    if mode != "music_only":
        delivery = voice.get("delivery") or {}
        lines.extend([
            "- 语言：%s" % (_plain(voice.get("language")) or "未指定"),
            "- 音色方向：%s" % (_plain(voice.get("voice_type")) or "未指定"),
            "- 表达语气：%s" % (_plain(delivery.get("tone")) or "未指定"),
        ])
        for key, label in (("pace", "语速"), ("articulation", "吐字"),
                           ("emphasis", "重音"), ("ending", "收句")):
            if delivery.get(key):
                lines.append("- %s：%s" % (label, _plain(delivery[key])))
    if contract.get("master_audio"):
        master = contract["master_audio"]
        lines.extend([
            "",
            "## 当前可试听内容",
            "",
            "- 已绑定客户提供或既有母音轨；它不是本阶段生成的声音。",
            "- 本地音轨：[%s](%s)" % (
                _plain(os.path.basename(master["path"])), master["path"]),
        ])
    else:
        lines.extend([
            "",
            "## 试听边界",
            "",
            "- 当前没有独立声音模型，因此本页没有可播放的试听音轨。",
            "- 第一次真实试听：单段测试片 `test_segment`。",
            "- 测试片必须同时检查：真实音轨、台词准确度、音色/语气、口型同步。",
            "- 测试片不通过时不能进入完整视频批次。",
        ])
    lines.extend([
        "",
        "## 确认范围",
        "",
        "- 确认本页代表接受声音方向，不代表已经听过模型生成的声音。",
        "- 正式生成由 `%s` 负责；声音与画面、口型一次生成。" % VOICE_OWNER,
        "- 任何声音模式、语言、音色、语气或 BGM 变化都必须重新展示和确认。",
        "",
        "## 版本绑定",
        "",
        "- 客户：`%s`" % _plain(client),
        "- Run：`%s`" % _plain(run_id),
        "- 选择 SHA-256：`%s`" % choice_sha256,
        "- Voice brief SHA-256：`%s`" % voice_brief_sha256,
        "- Audio contract SHA-256：`%s`" % contract_sha256,
        "",
    ])
    return "\n".join(lines)


def _write_immutable(path, data, *, label):
    if os.path.exists(path):
        with open(path, "rb") as handle:
            if handle.read() != data:
                raise ValueError("%s_IMMUTABLE_PATH_CONFLICT" % label.upper())
    else:
        atomic_write_bytes(path, data, mode=0o600, label=label)
    return path


def write_stage_artifacts(choice, output_root, *, client, run_id, master_path=None):
    """Write one immutable, content-addressed audio-direction artifact set."""
    output_root = require_contained_path(
        ROOT, output_root, label="audio_output_root", must_exist=False)
    os.makedirs(output_root, exist_ok=True)
    choice = normalize_choice(choice)
    voice_brief = compile_voice_brief(choice)
    contract = create(
        choice["mode"], voice_brief=voice_brief, master_path=master_path)
    choice_sha = _canonical_sha256(choice)
    voice_sha = _canonical_sha256(voice_brief)
    contract_sha = _canonical_sha256(contract)
    preview = compile_preview(
        choice, contract, choice_sha256=choice_sha,
        voice_brief_sha256=voice_sha, contract_sha256=contract_sha,
        client=client, run_id=run_id)
    preview_bytes = preview.encode("utf-8")
    preview_sha = hashlib.sha256(preview_bytes).hexdigest()
    specs = (
        ("audio_choice.%s.json" % choice_sha[:12], _canonical_bytes(choice), "audio_choice"),
        ("voice_brief.%s.json" % voice_sha[:12], _canonical_bytes(voice_brief), "voice_brief"),
        ("audio_contract.%s.json" % contract_sha[:12], _canonical_bytes(contract), "audio_contract"),
        ("%s%s.%s.md" % (PREVIEW_PREFIX, contract_sha[:12], preview_sha[:12]),
         preview_bytes, "audio_preview"),
    )
    paths = []
    for filename, data, label in specs:
        path = require_contained_path(
            ROOT, os.path.join(output_root, filename), label=label, must_exist=False)
        paths.append(_write_immutable(path, data, label=label))
    if master_path:
        paths.append(os.path.abspath(master_path))
    return {
        "choice": paths[0], "voice_brief": paths[1], "contract": paths[2],
        "preview": paths[3], "master_audio": paths[4] if master_path else None,
        "outputs": paths,
    }


def prepare_stage(manifest_path, choice_path, *, master_path=None):
    """Own the audio stage transaction from validated choice to pending review."""
    import run_manifest

    manifest_path = require_contained_path(
        ROOT, manifest_path, label="audio_manifest", must_exist=False)
    choice_path = require_contained_path(
        ROOT, choice_path, label="audio_choice", must_exist=True)
    with open(choice_path, encoding="utf-8") as handle:
        choice = normalize_choice(json.load(handle))
    manifest_path = require_contained_path(
        ROOT, manifest_path, label="audio_manifest", must_exist=True)
    if master_path:
        master_path = require_contained_path(
            ROOT, master_path, label="master_audio", must_exist=True)

    manifest = run_manifest.load_manifest(manifest_path)
    if run_manifest.next_required_stage(manifest) != "audio":
        raise ValueError("AUDIO_STAGE_NOT_CURRENT")
    expected_revision = int(manifest.get("revision") or 0)
    run_manifest.mark_generation_started(manifest, "audio")
    input_record = run_manifest.file_record(choice_path)
    manifest["generation"]["audio"]["input_contract"] = input_record
    run_manifest.save_manifest(
        manifest, manifest_path, expected_revision=expected_revision)
    try:
        result = write_stage_artifacts(
            choice, run_manifest.run_output_root(manifest),
            client=manifest["client"], run_id=manifest["run_id"],
            master_path=master_path)
        latest = run_manifest.load_manifest(manifest_path)
        generation = (latest.get("generation") or {}).get("audio") or {}
        if generation.get("status") != "running":
            raise ValueError("AUDIO_STAGE_TRANSACTION_LOST")
        if (generation.get("input_contract") != input_record or
                not run_manifest.file_record_is_current(input_record)):
            raise ValueError("AUDIO_CHOICE_CHANGED_DURING_PREPARE")
        finish_revision = int(latest.get("revision") or 0)
        run_manifest.mark_generation_finished(latest, "audio", result["outputs"])
        latest["generation"]["audio"]["input_contract"] = input_record
        run_manifest.save_manifest(
            latest, manifest_path, expected_revision=finish_revision)
        result["manifest"] = manifest_path
        result["generation_status"] = "pending_approval"
        return result
    except (OSError, ValueError, TypeError, RuntimeError) as exc:
        run_manifest.record_generation_failure_if_running(
            manifest_path, "audio", exc, error_code="AUDIO_STAGE_PREPARE_FAILED")
        raise


def approved_direction_from_manifest(manifest):
    """Return the exact approved audio direction and its immutable evidence."""
    import run_manifest

    if not run_manifest.approval_is_current(manifest, "audio"):
        raise ValueError("APPROVED_AUDIO_DIRECTION_REQUIRED")
    generation = (manifest.get("generation") or {}).get("audio") or {}
    candidates = []
    for record in generation.get("artifacts") or []:
        if not isinstance(record, dict) or not run_manifest.file_record_is_current(record):
            continue
        path = record.get("path")
        if not str(path).lower().endswith(".json"):
            continue
        try:
            value = _load_json(path)
        except (OSError, ValueError, json.JSONDecodeError):
            continue
        if value.get("audio_mode") in AUDIO_MODES:
            candidates.append((record, value))
    if len(candidates) != 1:
        raise ValueError("APPROVED_AUDIO_DIRECTION_AMBIGUOUS")
    artifact, contract = candidates[0]
    validate(contract)
    return {
        "contract": contract,
        "artifact": artifact,
        "stage_input_fingerprint": run_manifest.stage_input_fingerprint(
            manifest, "audio", refresh=True),
    }


def _load_json(path):
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def _legacy_create(argv):
    parser = argparse.ArgumentParser(description="Create a formal audio direction contract")
    parser.add_argument("--mode", choices=sorted(AUDIO_MODES), required=True)
    parser.add_argument("--voice-brief")
    parser.add_argument("--master-audio")
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    brief = _load_json(args.voice_brief) if args.voice_brief else None
    contract = create(args.mode, voice_brief=brief, master_path=args.master_audio)
    atomic_write_json(args.out, contract)
    print(json.dumps({"ok": True, "out": os.path.abspath(args.out)}, ensure_ascii=False))
    return 0


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] != "prepare":
        return _legacy_create(argv)
    parser = argparse.ArgumentParser(
        description="Validate all voice choices, then atomically prepare the audio stage")
    parser.add_argument("prepare")
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--choice", required=True)
    parser.add_argument("--master-audio")
    args = parser.parse_args(argv)
    result = prepare_stage(
        args.manifest, args.choice, master_path=args.master_audio)
    print(json.dumps({"ok": True, **result}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(json.dumps({"ok": False, "error": str(exc),
                          "error_type": type(exc).__name__}, ensure_ascii=False))
        raise SystemExit(2)
